/**
 * Build 194 — stage owner-approved AAC for a private signed iOS build.
 * Never commits or uploads music; call only in an owner-controlled checkout.
 * Usage: node scripts/stage-approved-startup-audio.mjs /private/path/approved.m4a
 */
import {readFile, mkdir, writeFile, rename, rm, chmod} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {LOCKED_GUARDIAN_MUSIC} from './verify-approved-soundtrack.mjs';

export const FRONTEND_ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const PRIVATE_SOURCE_RELATIVE='components/staarwardd/startup-approved-soundtrack-source.native.ts';
export const AUDIO_RELATIVE='assets/audio/Starward_Guardian_Approved_AAC_iOS.m4a';

export function generatedNativeSource(expected=LOCKED_GUARDIAN_MUSIC){
 if(expected.filename!=='Starward_Guardian_Approved_AAC_iOS.m4a')throw Error('unexpected_approved_audio_filename');
 return [
  '/* PRIVATE BUILD GENERATED BY VERIFIED LOCAL STAGING — DO NOT COMMIT.',
  ' * Approved audio fingerprint: '+expected.sha256,
  ' * This import is included only when the real approved AAC is present.',
  ' */',
  'import type { AudioSource } from "expo-audio";',
  'const approvedStartupSoundtrackSource: AudioSource = require("@/assets/audio/Starward_Guardian_Approved_AAC_iOS.m4a");',
  'export default approvedStartupSoundtrackSource;',
  ''
 ].join('\n');
}

export async function stageApprovedStartupAudio({inputFile,frontendRoot=FRONTEND_ROOT,expected=LOCKED_GUARDIAN_MUSIC}={}){
 if(!inputFile || typeof inputFile!=='string')throw Error('approved_audio_input_required');
 const source=await readFile(inputFile);
 if(source.length!==expected.bytes)throw Error('approved_audio_size_mismatch');
 if(source.length<32 || source.toString('ascii',4,8)!=='ftyp')throw Error('approved_audio_invalid_mp4_container');
 const digest=createHash('sha256').update(source).digest('hex');
 if(digest!==expected.sha256)throw Error('approved_audio_hash_mismatch');
 const dest=path.join(frontendRoot,AUDIO_RELATIVE);
 const destModule=path.join(frontendRoot,PRIVATE_SOURCE_RELATIVE);
 await mkdir(path.dirname(dest),{recursive:true});
 await mkdir(path.dirname(destModule),{recursive:true});
 const suffix='.stage-'+process.pid;
 const tempAudio=dest+suffix;
 const tempModule=destModule+suffix;
 try{
  await writeFile(tempAudio,source,{mode:0o600});
  await writeFile(tempModule,generatedNativeSource(expected),{mode:0o600});
  await rename(tempAudio,dest);
  await rename(tempModule,destModule);
  await chmod(dest,0o600);
  await chmod(destModule,0o600);
 }finally{
  await Promise.all([rm(tempAudio,{force:true}),rm(tempModule,{force:true})]);
 }
 return {sha256:digest,bytes:source.length,stagedAudioPath:dest,stagedNativeModulePath:destModule,
   note:'PRIVATE: requires local EAS upload inspection and actual iPhone test; never commit these files.'};
}

export async function verifyStagedNativeSource(frontendRoot=FRONTEND_ROOT,expected=LOCKED_GUARDIAN_MUSIC){
 const moduleFile=path.join(frontendRoot,PRIVATE_SOURCE_RELATIVE);
 const actual=await readFile(moduleFile,'utf8');
 if(actual!==generatedNativeSource(expected))throw Error('approved_audio_bundle_module_mismatch');
 return {verified:true,sourceModule:PRIVATE_SOURCE_RELATIVE};
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 stageApprovedStartupAudio({inputFile:process.argv[2]}).then(x=>{
  process.stdout.write(JSON.stringify(x,null,2)+'\n');
 }).catch(err=>{
  process.stderr.write('Approved soundtrack staging refused: '+String(err?.message??err)+'\n');
  process.exitCode=1;
 });
}
